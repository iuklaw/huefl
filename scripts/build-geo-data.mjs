// Generates the offline geo data for the schedule's location picker:
//   src/lib/zones.json      IANA time zone -> country codes + coordinates (zone1970.tab)
//   src/lib/world-land.ts   land outlines as one SVG path, equirectangular,
//                           x = lon + 180 (0…360), y = 90 − lat (0…180)
// Run once after changing the sources: node scripts/build-geo-data.mjs
// Needs the dev dependencies world-atlas and topojson-client, and the system
// tz database (/usr/share/zoneinfo).

import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";

// --- Zones ------------------------------------------------------------------------

function degrees(text) {
  // ±DDMM[SS] or ±DDDMM[SS]
  const sign = text[0] === "-" ? -1 : 1;
  const digits = text.slice(1);
  const degLen = digits.length === 4 || digits.length === 6 ? 2 : 3;
  const d = Number(digits.slice(0, degLen));
  const m = Number(digits.slice(degLen, degLen + 2));
  const s = Number(digits.slice(degLen + 2) || 0);
  return Math.round(sign * (d + m / 60 + s / 3600) * 100) / 100;
}

const zones = readFileSync("/usr/share/zoneinfo/zone1970.tab", "utf8")
  .split("\n")
  .filter((line) => line && !line.startsWith("#"))
  .map((line) => {
    const [countries, coords, id] = line.split("\t");
    const [, lat, lon] = coords.match(/^([+-]\d+)([+-]\d+)$/);
    return { id, countries: countries.split(","), lat: degrees(lat), lon: degrees(lon) };
  })
  .sort((a, b) => a.id.localeCompare(b.id));
writeFileSync("src/lib/zones.json", JSON.stringify(zones));
console.log(`zones.json: ${zones.length} zones`);

// --- Land -------------------------------------------------------------------------

const topology = JSON.parse(readFileSync("node_modules/world-atlas/land-110m.json", "utf8"));
const land = feature(topology, topology.objects.land);
const round = (n) => Math.round(n * 10) / 10;
let d = "";
for (const f of land.features) {
  const polygons = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const polygon of polygons) {
    for (const ring of polygon) {
      // Rings crossing the antimeridian jump by ~360°: unwrap them so they
      // stay continuous, and draw a copy shifted back by 360° - the map's
      // viewBox clips each copy to its half.
      const unwrapped = [];
      for (const [lon, lat] of ring) {
        let x = lon;
        const last = unwrapped.at(-1);
        if (last) while (x - last[0] > 180) x -= 360;
        if (last) while (last[0] - x > 180) x += 360;
        unwrapped.push([x, lat]);
      }
      const lons = unwrapped.map(([x]) => x);
      const shifts = [0];
      if (Math.max(...lons) > 180) shifts.push(-360);
      if (Math.min(...lons) < -180) shifts.push(360);
      for (const shift of shifts) {
        let previous = null;
        unwrapped.forEach(([lon, lat], i) => {
          const key = `${round(lon + shift + 180)},${round(90 - lat)}`;
          if (key === previous) return;
          d += (i === 0 ? "M" : "L") + key;
          previous = key;
        });
        d += "Z";
      }
    }
  }
}
writeFileSync(
  "src/lib/world-land.ts",
  "// Generated by scripts/build-geo-data.mjs from Natural Earth 110m (world-atlas).\n" +
    "// Land outlines, equirectangular: x = lon + 180, y = 90 − lat.\n" +
    `export const WORLD_LAND = "${d}";\n`,
);
console.log(`world-land.ts: ${(d.length / 1024).toFixed(0)} KB`);
